import type { ComponentProps } from 'react'

import ChannelsPageChannelCards from '../components/ChannelsPageChannelCards'
import ChannelsPageDiagnosticsModal from '../components/ChannelsPageDiagnosticsModal'
import ChannelsPageModelConfigModal from '../components/ChannelsPageModelConfigModal'
import ChannelsPagePairingModal from '../components/ChannelsPagePairingModal'
import type { ChannelsPageChannelInfo } from './channels-page-data-contract'
import type {
  ChannelsPageSurfaceCompositionOptions,
  ChannelsPageSurfaceCompositionResult,
} from './channels-page-surface-composition-contract'
import { useChannelsPageMainSurfaceProps } from './channels-page-main-surface-props'
import { useChannelsPageModalProps } from './channels-page-modal-props'
import { useChannelsPageModelModalProps } from './channels-page-model-modal-props'
import { useChannelsPageTargetStateGroups } from './channels-page-target-state-groups'

export function useChannelsPageSurfaceComposition({
  channels,
  refreshing,
  error,
  legacyFeishuAgentIds,
  setError,
  handleRefreshChannels,
  handleOpenAddChannel,
  togglingChannelId,
  removingChannelId,
  repairingPluginChannelId,
  handleOpenModelConfig,
  handleToggleChannelEnabled,
  handleOpenPairing,
  handleOpenDiagnostics,
  handleRepairFeishuPlugin,
  handleRemoveChannel,
  showConfigModal,
  handleChannelConfigBack,
  configStep,
  selectedChannelId,
  selectedConfigTarget,
  handleConfigDone,
  setSelectedChannelId,
  setSelectedConfigTarget,
  setConfigStep,
  showPairingModal,
  selectedPairingChannel,
  selectedPairingTarget,
  handlePairingClose,
  handlePairingDone,
  showDiagnosticsModal,
  selectedDiagnosticsChannel,
  selectedDiagnosticsTarget,
  handleDiagnosticsClose,
  refreshChannelsInBackground,
  showModelModal,
  selectedModelChannel,
  closeModelModal,
  currentRuntimeModel,
  modelModalError,
  loadingModelContext,
  modelOptions,
  selectedModelValue,
  savingModel,
  setSelectedModelValue,
  handleSaveBotModel,
  deriveTargetState,
  deriveChannelStatusBadges,
  getChannelCardSummary,
  getFeishuSharedStatusAlert,
  getFeishuProvisionSourceDescription,
  shouldShowPluginStatus,
  shouldShowFeishuPluginRepairAction,
  getFeishuPairingModalSummary,
  getFeishuRuntimeSummaryAlertColor,
  getFeishuDiagnosticsModalTitle,
  getFeishuChannelDisplayName,
  repairFeishuPlugin,
}: ChannelsPageSurfaceCompositionOptions): ChannelsPageSurfaceCompositionResult {
  const {
    configTargetState,
    pairingTargetState,
    diagnosticsTargetState,
  } = useChannelsPageTargetStateGroups({
    channels,
    repairingPluginChannelId,
    refreshChannels: refreshChannelsInBackground,
    deriveTargetState,
    config: {
      active: configStep === 'pairing-code',
      target: selectedConfigTarget,
    },
    pairing: {
      active: showPairingModal,
      target: selectedPairingTarget,
      fallbackChannel: selectedPairingChannel,
    },
    diagnostics: {
      active: showDiagnosticsModal,
      target: selectedDiagnosticsTarget,
      fallbackChannel: selectedDiagnosticsChannel,
    },
  })

  const {
    configModalProps,
    pairingModalProps,
    diagnosticsModalProps,
  } = useChannelsPageModalProps({
    showConfigModal,
    handleChannelConfigBack,
    configStep,
    selectedChannelId,
    selectedConfigTarget,
    handleConfigDone,
    setSelectedChannelId,
    setSelectedConfigTarget,
    setConfigStep,
    configTargetState: {
      targetKey: configTargetState.pairingKey,
      statusAlert: configTargetState.sharedStatusAlert,
      repairing: configTargetState.repairing,
      canRepair: configTargetState.canRepair,
      statusPending: configTargetState.statusPending,
      missingAfterRefresh: configTargetState.missingAfterRefresh,
      blockedBySharedStatus: configTargetState.blockedBySharedStatus,
      refreshingTargetChannel: configTargetState.refreshingTargetChannel,
      channel: configTargetState.targetChannel,
      refreshTargetChannelStatus: configTargetState.refreshTargetChannelStatus,
    },
    showPairingModal,
    pairingTargetState: {
      targetKey: pairingTargetState.pairingKey,
      statusAlert: pairingTargetState.sharedStatusAlert,
      repairing: pairingTargetState.repairing,
      canRepair: pairingTargetState.canRepair,
      statusPending: pairingTargetState.statusPending,
      missingAfterRefresh: pairingTargetState.missingAfterRefresh,
      blockedBySharedStatus: pairingTargetState.blockedBySharedStatus,
      refreshingTargetChannel: pairingTargetState.refreshingTargetChannel,
      channel: pairingTargetState.channelForSurface,
      refreshTargetChannelStatus: pairingTargetState.refreshTargetChannelStatus,
    },
    handlePairingClose,
    handlePairingDone,
    showDiagnosticsModal,
    diagnosticsTargetState: {
      targetKey: diagnosticsTargetState.pairingKey,
      statusAlert: diagnosticsTargetState.sharedStatusAlert,
      repairing: diagnosticsTargetState.repairing,
      canRepair: diagnosticsTargetState.canRepair,
      statusPending: diagnosticsTargetState.statusPending,
      missingAfterRefresh: diagnosticsTargetState.missingAfterRefresh,
      refreshingTargetChannel: diagnosticsTargetState.refreshingTargetChannel,
      channel: diagnosticsTargetState.channelForSurface,
      fallbackChannel: selectedDiagnosticsChannel,
      refreshTargetChannelStatus: diagnosticsTargetState.refreshTargetChannelStatus,
    },
    handleDiagnosticsClose,
    deriveChannelStatusBadges,
    getFeishuPairingModalSummary,
    getFeishuRuntimeSummaryAlertColor,
    getFeishuDiagnosticsModalTitle,
    getFeishuChannelDisplayName,
    repairFeishuPlugin,
  })

  const {
    topPanelProps,
    channelListPanelProps,
    channelCardsProps,
  } = useChannelsPageMainSurfaceProps({
    refreshing,
    error,
    legacyFeishuAgentIds,
    handleRefreshChannels,
    handleOpenAddChannel,
    setError,
    channels,
    togglingChannelId,
    removingChannelId,
    repairingPluginChannelId,
    handleOpenModelConfig,
    handleToggleChannelEnabled,
    handleOpenPairing,
    handleOpenDiagnostics,
    handleRepairFeishuPlugin,
    handleRemoveChannel,
    deriveChannelStatusBadges,
    getChannelCardSummary,
    getFeishuSharedStatusAlert,
    getFeishuProvisionSourceDescription,
    shouldShowPluginStatus,
    shouldShowFeishuPluginRepairAction,
  })

  const {
    modelConfigModalProps,
  } = useChannelsPageModelModalProps({
    showModelModal,
    selectedModelChannel,
    closeModelModal,
    currentRuntimeModel,
    modelModalError,
    loadingModelContext,
    modelOptions,
    selectedModelValue,
    savingModel,
    setSelectedModelValue,
    handleSaveBotModel,
  })

  return {
    topPanelProps,
    channelListPanelProps,
    channelCardsProps,
    configModalProps,
    pairingModalProps,
    modelConfigModalProps,
    diagnosticsModalProps,
  }
}
